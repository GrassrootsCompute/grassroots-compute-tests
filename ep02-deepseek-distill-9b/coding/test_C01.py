import unittest
from solution import add_months


class T(unittest.TestCase):
    def test_cases(self):
        cases = [
            ('2026-01-31', 1, '2026-02-28'),
            ('2028-01-31', 1, '2028-02-29'),
            ('2026-03-31', -1, '2026-02-28'),
            ('2026-12-15', 1, '2027-01-15'),
            ('2026-01-15', -1, '2025-12-15'),
            ('2026-05-31', 1, '2026-06-30'),
            ('2026-07-09', 0, '2026-07-09'),
            ('2026-01-31', 12, '2027-01-31'),
            ('2024-02-29', 12, '2025-02-28'),
            ('2024-02-29', 48, '2028-02-29'),
            ('2026-10-31', -8, '2026-02-28'),
            ('2026-01-01', -13, '2024-12-01'),
        ]
        for d, n, want in cases:
            with self.subTest(d=d, n=n):
                self.assertEqual(add_months(d, n), want)


if __name__ == '__main__':
    unittest.main()
